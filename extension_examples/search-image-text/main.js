function normalize(text) {
  return text.normalize("NFKC").toLowerCase().replace(/\s+/gu, " ").trim();
}

async function run(context, api) {
  const m = messages[context.locale] || messages.en;
  let input;
  try { input = JSON.parse(context.inputs.rules); } catch { throw new Error(m[0]); }
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new Error(m[0]);
  const entries = Object.entries(input);
  const colors = new Set(["grey", "blue", "red", "yellow", "green", "pink", "purple", "cyan", "orange"]);
  if (!entries.length || entries.length > 128) throw new Error(m[0]);
  const rules = entries.map(([keyword, color]) => {
    if (!normalize(keyword) || keyword.length > 512 || typeof color !== "string" || !colors.has(color))
      throw new Error(m[0]);
    return [normalize(keyword), color];
  });
  const photos = context.items.filter(item => item.type === "photo");
  const skipped = context.items.length - photos.length;
  if (!photos.length) { api.ui.setOutput(m[8]); return; }
  const output = [];
  const append = (text, item) => {
    const line = {text};
    if (item) line.itemId = item.id;
    output.push(line);
    // Keep output bounded without losing the final summary on large selections.
    if (output.length > 100) output.shift();
    api.ui.setOutputLines(output);
  };
  append(m[1]);
  api.ui.setProgress(0, photos.length);
  let matched = 0, failed = 0;
  for (let i = 0; i < photos.length; ++i) {
    const item = photos[i];
    const name = item.name.slice(0, 200);
    append(`${m[2]} ${i + 1}/${photos.length}: ${name}`, item);
    try {
      const result = await api.media.recognizeText(item.id);
      if (result.limited) append(`${m[7]}: ${name}`, item);
      const text = normalize(result.text);
      const rule = rules.find(([keyword]) => text.includes(keyword));
      if (rule) {
        const changed = await api.media.setTag([item.id], rule[1]);
        ++matched;
        append(`${changed ? m[3] : m[4]} (${(colorNames[context.locale] || colorNames.en)[rule[1]]}): ${name}`, item);
      } else append(`${m[5]}: ${name}`, item);
    } catch (error) {
      if (error.name === "OcrRuntimeError") throw new Error(m[9]);
      ++failed;
      append(`${m[6]}: ${name} (${String(error.message).slice(0, 160)})`, item);
    }
    api.ui.setProgress(i + 1, photos.length);
  }
  const counts = [photos.length, photos.length, matched, failed, skipped];
  append(m[10].replace(/\{(\d)\}/g, (_, index) => String(counts[Number(index)])));
}
